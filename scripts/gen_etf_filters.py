#!/usr/bin/env python3
"""Regenerate ``finvizfinance/etf_constants.py`` from the live ETF screener.

The ETF screener page (``/screener/etf``) embeds its filter definitions as
JSON. This script reads the ``tab: "etf"`` filters from it and writes them out
in the ``filter_dict`` shape. Elite-only filters and options are left out:
a free account cannot use them.

Usage::

    python scripts/gen_etf_filters.py            # fetch from finviz
    python scripts/gen_etf_filters.py page.html  # read a saved page
"""

import json
import os
import re
import sys
from typing import Any

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

from finvizfinance import util  # noqa: E402

URL = "https://finviz.com/screener/etf"
OUT = os.path.join(os.path.dirname(__file__), "..", "finvizfinance", "etf_constants.py")

HEADER = '''"""
ETF screener filters (finviz ``/screener/etf``).

Generated by ``scripts/gen_etf_filters.py`` from the filter definitions
embedded in the finviz ETF screener page. Elite-only filters and options are
left out. Do not edit by hand.
"""

from __future__ import annotations

ETF_FILTERS: dict[str, dict] = {
'''


def parse_filters(html: str) -> list[dict[str, Any]]:
    decoder = json.JSONDecoder()
    filters = []
    for match in re.finditer(r'\{"key":"etf_\w+","tab":"etf"', html):
        obj, _ = decoder.raw_decode(html, match.start())
        if obj.get("isEliteOnly"):
            continue
        obj["options"] = [o for o in obj["options"] if not o.get("isEliteOnly")]
        filters.append(obj)
    if not filters:
        raise SystemExit("No ETF filters found in the page.")
    return filters


def render(filters: list[dict[str, Any]]) -> str:
    lines = [HEADER.rstrip("\n")]
    for f in filters:
        lines.append(f"    {json.dumps(f['title']['short'])}: {{")
        lines.append(f'        "prefix": {json.dumps(f["key"])},')
        lines.append('        "option": {')
        for o in f["options"]:
            label = json.dumps(o["label"], ensure_ascii=False)
            lines.append(f"            {label}: {json.dumps(o['value'])},")
        lines.append("        },")
        lines.append("    },")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> None:
    if len(sys.argv) > 1:
        with open(sys.argv[1], encoding="utf8") as fh:
            html = fh.read()
    else:
        html = str(util.web_scrap(URL))
    filters = parse_filters(html)
    with open(OUT, "w", encoding="utf8", newline="\n") as fh:
        fh.write(render(filters))
    print(f"Wrote {len(filters)} filters: {[f['title']['short'] for f in filters]}")


if __name__ == "__main__":
    main()
